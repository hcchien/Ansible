import 'package:flutter/widgets.dart';

import 'app_localizations.dart';

class SubpageL10n {
  const SubpageL10n(this.languageCode);

  final String languageCode;

  static SubpageL10n of(BuildContext context) {
    if (Localizations.of<AppLocalizations>(context, AppLocalizations) == null) {
      return const SubpageL10n('zh');
    }
    return SubpageL10n(Localizations.localeOf(context).languageCode);
  }

  String t(String key) {
    return (_strings[languageCode] ?? _strings['en']!)[key] ??
        _strings['en']![key] ??
        key;
  }

  String f(String key, Map<String, Object> values) {
    var text = t(key);
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return text;
  }
}

