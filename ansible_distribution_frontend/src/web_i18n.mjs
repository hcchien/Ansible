let currentLocale = DEFAULT_LOCALE;

export function setCurrentLocale(locale) {
  currentLocale = resolveLocale(locale);
  return currentLocale;
}

export function getCurrentLocale() {
  return currentLocale;
}

export function resolveLocale(locale) {
  const value = String(locale ?? '').replaceAll('_', '-');
  if (value === 'en' || value.startsWith('en-')) return 'en';
  if (value === 'zh' || value.startsWith('zh-')) return 'zh-Hant';
  return DEFAULT_LOCALE;
}

export function t(key, params = {}, locale = currentLocale) {
  const resolvedLocale = resolveLocale(locale);
  const template = TRANSLATIONS[resolvedLocale]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  return interpolate(template, params);
}

export function getTranslationKeys(locale = DEFAULT_LOCALE) {
  return Object.keys(TRANSLATIONS[resolveLocale(locale)] ?? {}).sort();
}

function interpolate(template, params) {
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) =>
    params[name] === undefined ? `{${name}}` : String(params[name]),
  );
}
